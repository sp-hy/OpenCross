"""Writes src/import/console_font_chars.inc: the character order of the console's kanji font.

Run with:  python -I tools/py/console_font_chars.py [--check]

The font holds one cell per defined character of JIS X 0208 rows 1-8 (symbols, alphanumerics, kana, Greek, Cyrillic, box
drawing) and rows 16-47 (level-1 kanji), in code order. The table lists {Unicode code point, cell} sorted by code point, from the
standard Shift-JIS code page; where Windows code page 932 gives a character another code point (wave dash, minus, ...), that
code point names the same cell too.
"""
import os
import sys

ROWS = list(range(1, 9)) + list(range(16, 48))
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "src", "import", "console_font_chars.inc")


def sjis(row, cell):
    lead = (row + 1) // 2 + 0x80
    trail = (cell + 0x3F + (1 if cell >= 64 else 0)) if row % 2 else cell + 0x9E
    return bytes([lead, trail])


def entries():
    pairs = {}
    index = 0
    for row in ROWS:
        for cell in range(1, 95):
            code = sjis(row, cell)
            try:
                ch = code.decode("shift_jis")
            except UnicodeDecodeError:
                continue
            pairs.setdefault(ord(ch), index)
            alt = code.decode("cp932")
            pairs.setdefault(ord(alt), index)
            index += 1
    return index, sorted(pairs.items())


def render():
    count, pairs = entries()
    lines = ["// Generated by tools/py/console_font_chars.py; do not edit by hand.",
             "// kConsoleFontCells: the number of cells (defined characters of JIS X 0208 rows 1-8 and 16-47).",
             f"inline constexpr int kConsoleFontCells = {count};",
             "// kConsoleFontChars: {Unicode code point, cell}, ascending by code point.",
             "inline constexpr struct { unsigned short cp; unsigned short cell; } kConsoleFontChars[] = {"]
    for i in range(0, len(pairs), 8):
        lines.append("  " + ",".join("{0x%04X,%d}" % pair for pair in pairs[i:i + 8]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8", newline="") as f:
            same = f.read() == text
        print("up to date" if same else "differs")
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
